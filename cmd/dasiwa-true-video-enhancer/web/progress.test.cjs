'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { view, progressFor } = require('./progress.js');
const now = Date.parse('2026-01-01T00:10:00Z');
const job = { status:'running', started_at:'2026-01-01T00:00:00Z', progress_done:10,
 progress_total:100, progress_throughput:2, progress_stage:'rendering', progress_updated_at:new Date(now).toISOString() };
assert.match(view(job, now).detail, /ETA ≈ 45s/);
assert.match(view(job, now+1000).detail, /ETA ≈ 44s/);
assert.match(view({...job, started_at:'2020-01-01T00:00:00Z'},now).detail, /ETA ≈ 45s/);
assert.match(view({...job,progress_throughput:4},now).detail, /ETA ≈ 23s/);
assert.match(view({...job,progress_throughput:1},now).detail, /ETA ≈ 1m 30s/);
assert.equal(view({...job,status:'queued'},now).detail,'');
assert.equal(view({...job,progress_stage:'preparing'},now).label,'PREPARING');
assert.equal(view({...job,progress_done:0,progress_throughput:0},now).label,'PREPARING');
assert.match(view({...job,progress_throughput:0},now).detail,/Measuring throughput/);
assert.equal(view(job,now+31000).label,'WAITING FOR PROGRESS');
assert.doesNotMatch(view(job,now+31000).detail,/ETA ≈/);
assert.equal(view({...job,progress_stage:'finalizing'},now).label,'FINALIZING');
assert.equal(view({...job,progress_done:100},now).percent,99);
for(const status of ['done','cancelled','error']) assert.equal(view({...job,status},now).detail,'');
assert.equal(view({...job,status:'done'},now).percent,100);
assert.equal(progressFor({...job,progress_throughput:Infinity}),null);
assert.equal(progressFor({...job,progress_done:101}),null);
assert.equal(view({...job,progress_done:0,logs:['wrote 99/100 frames']},now).label,'PREPARING');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
assert.doesNotMatch(html,/etaValue|progressValue|eta-card/);
assert.doesNotMatch(fs.readFileSync(__dirname+'/app.js','utf8'),/parseFrameProgress|renderJobProgress/);
console.log('Progress pure regressions passed: polling prediction, delayed start, throughput changes, queued, preparing, stale, finalizing, terminal, finite contract, no duplicate preview ETA.');
